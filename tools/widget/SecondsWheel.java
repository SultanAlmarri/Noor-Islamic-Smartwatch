import java.awt.Font;
import java.awt.font.FontRenderContext;
import java.awt.font.GlyphVector;
import java.awt.geom.AffineTransform;
import java.awt.geom.PathIterator;
import java.awt.geom.Rectangle2D;
import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.Locale;

/**
 * Builds the widgets' seconds wheels (0.9.14): the seconds "00" to "59" in Noor's own Plex Light, as vector drawables,
 * set around a wheel that Android's AnalogClock turns as its second hand.
 *
 * Why: on a home screen only Android can change a widget every second without Noor running, and its digital clocks
 * (Chronometer, TextClock) write the phone's digits; fonts packed in an app are ignored there. An AnalogClock's second
 * hand, though, is any drawable, turned by Android one step (6 degrees) a second, on the real clock. So the hand is a
 * wheel of the 60 labels and the widget shows it through a window at the top: there, the label for this second stands
 * upright. "down" wheels count down (countdown to a prayer), "up" wheels count up (time since a prayer).
 *
 * Writes app/src/main/res/drawable/noor_sec_{latin,arabic}_NN.xml (the labels), noor_wheel_{latin,arabic}_{down,up}.xml
 * (the wheels), noor_wheel_blank.xml (the clock's dial and other hands, empty) and res/values/noor_wheel.xml (sizes the
 * widget code needs). Run from the repository root with JDK 17:
 *
 *     java tools/widget/SecondsWheel.java
 */
public class SecondsWheel {
    static final float FONT_DP = 28f;        // the countdown's size in the widgets
    static final float PAD_EM = 0.06f;       // above the tallest and below the lowest digit
    static final float GAP_EM = 0.32f;       // between two labels on the wheel (keeps the neighbours out of the window)
    static final String QUIET = "#80FFFFFF"; // the seconds are quieter, as on the home screen

    public static void main(String[] args) throws Exception {
        File root = new File(".");
        File fontFile = new File(root, "app/src/main/res/font/plex_arabic_light.ttf");
        File drawable = new File(root, "app/src/main/res/drawable");
        File values = new File(root, "app/src/main/res/values");
        Font font = Font.createFont(Font.TRUETYPE_FONT, fontFile).deriveFont(1000f); // 1 unit = 1/1000 em
        FontRenderContext frc = new FontRenderContext(new AffineTransform(), false, false);

        String[] sets = {"latin", "arabic"};
        char[] zero = {'0', (char) 0x660};
        // The box every label shares (and the bitmap of hours and minutes uses): from the tallest digit, sign or colon
        // to the lowest, in either set.
        double top = 0, bottom = 0, maxWidth = 0;
        double[] advance = new double[2];
        for (int s = 0; s < 2; s++) {
            for (int d = 0; d < 10; d++) {
                GlyphVector g = font.createGlyphVector(frc, String.valueOf((char) (zero[s] + d)));
                Rectangle2D b = g.getOutline().getBounds2D();
                top = Math.min(top, b.getMinY()); bottom = Math.max(bottom, b.getMaxY());
                advance[s] = Math.max(advance[s], g.getGlyphMetrics(0).getAdvance());
            }
            maxWidth = Math.max(maxWidth, 2 * advance[s]);
        }
        for (String other : new String[]{":", String.valueOf((char) 0x2212), "+"}) {
            Rectangle2D b = font.createGlyphVector(frc, other).getOutline().getBounds2D();
            top = Math.min(top, b.getMinY()); bottom = Math.max(bottom, b.getMaxY());
        }
        double pad = PAD_EM * 1000;
        double ascent = -top + pad;                 // baseline, from the top of the box
        double height = bottom - top + 2 * pad;
        double pitch = maxWidth + GAP_EM * 1000;    // from one label's centre to the next, along the wheel
        double centreRadius = pitch * 30 / Math.PI; // 60 labels around
        double radius = centreRadius + height / 2;  // the labels' tops touch the wheel's edge
        double wheel = 2 * radius;

        for (int s = 0; s < 2; s++) {
            double w = 2 * advance[s];
            for (int n = 0; n < 60; n++) {
                String label = String.format(Locale.ROOT, "%02d", n);
                StringBuilder digits = new StringBuilder();
                for (char c : label.toCharArray()) digits.append((char) (zero[s] + (c - '0')));
                StringBuilder path = new StringBuilder();
                for (int i = 0; i < 2; i++) {
                    GlyphVector g = font.createGlyphVector(frc, String.valueOf(digits.charAt(i)));
                    double x = i * advance[s] + (advance[s] - g.getGlyphMetrics(0).getAdvance()) / 2; // tabular
                    appendPath(path, g.getOutline((float) x, (float) ascent));
                }
                String xml = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
                    + "<!-- Generated by tools/widget/SecondsWheel.java: \"" + label + "\" for the widgets' seconds wheel. -->\n"
                    + "<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n"
                    + "    android:width=\"" + dp(w) + "dp\"\n    android:height=\"" + dp(height) + "dp\"\n"
                    + "    android:viewportWidth=\"" + num(w) + "\"\n    android:viewportHeight=\"" + num(height) + "\">\n"
                    + "    <path\n        android:fillColor=\"" + QUIET + "\"\n        android:pathData=\"" + path.toString().trim() + "\" />\n"
                    + "</vector>\n";
                write(new File(drawable, "noor_sec_" + sets[s] + "_" + label + ".xml"), xml);
            }
            for (String dir : new String[]{"down", "up"}) {
                StringBuilder xml = new StringBuilder("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
                    + "<!-- Generated by tools/widget/SecondsWheel.java: the seconds wheel (" + sets[s] + " digits, counting " + dir
                    + "). Turned by an AnalogClock as its second hand; label n stands upright at the top when the clock's\n"
                    + "     second is " + ("up".equals(dir) ? "n" : "(60 - n) mod 60") + ". -->\n"
                    + "<layer-list xmlns:android=\"http://schemas.android.com/apk/res/android\">\n"
                    + "    <item>\n        <shape android:shape=\"rectangle\">\n            <size android:width=\"" + dp(wheel)
                    + "dp\" android:height=\"" + dp(wheel) + "dp\" />\n        </shape>\n    </item>\n");
                for (int n = 0; n < 60; n++) {
                    // The clock turns the wheel clockwise by 6 degrees a second; a label at angle a (clockwise from the
                    // top) is at the top when the clock's second is -a/6.
                    int angle = "up".equals(dir) ? (360 - 6 * n) % 360 : (6 * n) % 360;
                    xml.append("    <item>\n        <rotate android:fromDegrees=\"").append(angle).append("\" android:toDegrees=\"").append(angle)
                        .append("\" android:pivotX=\"50%\" android:pivotY=\"50%\">\n            <layer-list>\n")
                        .append("                <item android:gravity=\"top|center_horizontal\" android:drawable=\"@drawable/noor_sec_")
                        .append(sets[s]).append("_").append(String.format(Locale.ROOT, "%02d", n)).append("\" />\n")
                        .append("            </layer-list>\n        </rotate>\n    </item>\n");
                }
                xml.append("</layer-list>\n");
                write(new File(drawable, "noor_wheel_" + sets[s] + "_" + dir + ".xml"), xml.toString());
            }
        }
        write(new File(drawable, "noor_wheel_blank.xml"), "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
            + "<!-- Generated by tools/widget/SecondsWheel.java: the seconds wheel's clock face and other hands, empty and as large as the wheel. -->\n"
            + "<shape xmlns:android=\"http://schemas.android.com/apk/res/android\" android:shape=\"rectangle\">\n"
            + "    <size android:width=\"" + dp(wheel) + "dp\" android:height=\"" + dp(wheel) + "dp\" />\n</shape>\n");
        write(new File(values, "noor_wheel.xml"), "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
            + "<!-- Generated by tools/widget/SecondsWheel.java: the widgets' countdown (0.9.14). -->\n<resources>\n"
            + "    <dimen name=\"noor_count_text\">" + dp(1000) + "dp</dimen>\n"
            + "    <dimen name=\"noor_count_ascent\">" + dp(ascent) + "dp</dimen>\n"
            + "    <dimen name=\"noor_count_height\">" + dp(height) + "dp</dimen>\n"
            + "    <dimen name=\"noor_count_window\">" + dp(maxWidth) + "dp</dimen>\n"
            + "    <dimen name=\"noor_count_wheel\">" + dp(wheel) + "dp</dimen>\n"
            + "</resources>\n");
        System.out.printf(Locale.ROOT, "box %.2f dp high (baseline %.2f), window %.2f dp, wheel %.1f dp%n", dp2(height), dp2(ascent), dp2(maxWidth), dp2(wheel));
    }

    static void appendPath(StringBuilder sb, java.awt.Shape shape) {
        PathIterator it = shape.getPathIterator(null);
        double[] c = new double[6];
        while (!it.isDone()) {
            switch (it.currentSegment(c)) {
                case PathIterator.SEG_MOVETO: sb.append('M').append(num(c[0])).append(',').append(num(c[1])); break;
                case PathIterator.SEG_LINETO: sb.append('L').append(num(c[0])).append(',').append(num(c[1])); break;
                case PathIterator.SEG_QUADTO: sb.append('Q').append(num(c[0])).append(',').append(num(c[1])).append(' ').append(num(c[2])).append(',').append(num(c[3])); break;
                case PathIterator.SEG_CUBICTO: sb.append('C').append(num(c[0])).append(',').append(num(c[1])).append(' ').append(num(c[2])).append(',').append(num(c[3])).append(' ').append(num(c[4])).append(',').append(num(c[5])); break;
                case PathIterator.SEG_CLOSE: sb.append('Z'); break;
            }
            it.next();
        }
    }

    static double dp2(double units) { return units / 1000 * FONT_DP; }
    static String dp(double units) { return String.format(Locale.ROOT, "%.2f", dp2(units)); }
    static String num(double v) { String s = String.format(Locale.ROOT, "%.1f", v); return s.endsWith(".0") ? s.substring(0, s.length() - 2) : s; }

    static void write(File f, String s) throws Exception { Files.write(f.toPath(), s.getBytes(StandardCharsets.UTF_8)); }
}
