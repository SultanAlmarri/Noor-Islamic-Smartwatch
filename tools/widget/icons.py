#!/usr/bin/env python3
"""
Writes the widgets' signs of the six times (0.23): app/src/main/res/drawable/widget_icon_*.xml, white vector
drawables tinted by the code. Drawn for Minhad (no outside artwork). Run from the repository root:

    python3 tools/widget/icons.py
"""
import os

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "app", "src", "main", "res", "drawable")
HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/widget/icons.py (0.23): the sign of %s on the widgets, '
        'white, tinted by the code. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" '
        'android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n')


def stroke(p, w=1.8):
    return (f'    <path android:pathData="{p}" android:strokeColor="#FFFFFFFF" android:strokeWidth="{w}" '
            'android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />\n')


def fill(p):
    return f'    <path android:pathData="{p}" android:fillColor="#FFFFFFFF" />\n'


def circle(x, y, r):
    return f"M{x - r},{y}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0z"


HORIZON = "M3,18.5H21"
STAR = "l0.55,1.25 1.25,0.55 -1.25,0.55 -0.55,1.25 -0.55,-1.25 -1.25,-0.55 1.25,-0.55z"

ICONS = {
    "fajr": ("Fajr (dawn: the first light over the horizon)",
             stroke(HORIZON) + stroke("M7.5,18.5A4.5,4.5 0 0,1 16.5,18.5") + fill("M18,4.6" + STAR) + fill("M6,6.4" + STAR)),
    "shuruq": ("Shuruq (the Sun rising)",
               stroke(HORIZON) + fill("M6.5,18.5A5.5,5.5 0 0,1 17.5,18.5z") + stroke("M12,6.2V8.8", 1.6)
               + stroke("M5.4,9.4L7.2,11.2", 1.6) + stroke("M18.6,9.4L16.8,11.2", 1.6)),
    "dhuhr": ("Dhuhr (the Sun high)",
              fill(circle(12, 12, 4.2)) + "".join(stroke(p, 1.6) for p in [
                  "M12,2.8V4.6", "M12,19.4V21.2", "M2.8,12H4.6", "M19.4,12H21.2",
                  "M5.5,5.5L6.8,6.8", "M17.2,17.2L18.5,18.5", "M5.5,18.5L6.8,17.2", "M17.2,6.8L18.5,5.5"])),
    "asr": ("Asr (the Sun lower, in the afternoon)",
            stroke(HORIZON) + fill(circle(13.5, 11, 3.6)) + "".join(stroke(p, 1.6) for p in [
                "M13.5,4.2V5.6", "M7.6,6.4L8.6,7.4", "M19.4,6.4L18.4,7.4", "M6.6,11H8", "M19,11H20.4"])),
    "maghrib": ("Maghrib (the Sun setting)",
                stroke(HORIZON) + fill("M6.5,18.5A5.5,5.5 0 0,1 17.5,18.5z") + stroke("M12,4.6V10", 1.6)
                + stroke("M9.6,7.7L12,10.1L14.4,7.7", 1.6)),
    "isha": ("Isha (night: the crescent and a star)",
             fill("M13.6,3.2A8.6,8.6 0 1,0 20.8,15.4A7,7 0 1,1 13.6,3.2z") + fill("M18.4,3.9" + STAR)),
}


def main():
    for k, (desc, body) in ICONS.items():
        with open(os.path.join(OUT, f"widget_icon_{k}.xml"), "w", encoding="utf-8") as f:
            f.write(HEAD % desc + body + "</vector>\n")
    print(f"wrote {len(ICONS)} signs")


if __name__ == "__main__":
    main()
