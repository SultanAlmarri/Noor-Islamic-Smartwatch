"""Write docs/prayer_comparison.md: engine vs every saved reference table."""
import csv, os, datetime as dt, sys
sys.path.insert(0, os.path.dirname(__file__))
import data, engine
from compare import env_for, astro_check

P = engine.Params()
EXPR = {ev: engine.event_seconds(P, ev) for ev in data.EVENTS}
REFDIR = os.path.join(os.path.dirname(__file__), "..", "reference_data")
COLS = ["fajr", "sunrise", "dhuhr", "asr", "maghrib", "isha"]
LABEL = dict(fajr="Fajr", sunrise="Shuruq", dhuhr="Dhuhr", asr="Asr", maghrib="Maghrib", isha="Isha")


def hm(s):
    s = int(s) % 86400
    return "%d:%02d" % (s // 3600, (s % 3600) // 60)


def table(fname):
    lines = [l for l in open(os.path.join(REFDIR, fname)) if not l.startswith("#")]
    head = [l for l in open(os.path.join(REFDIR, fname)) if l.startswith("#")]
    rows = list(csv.DictReader(lines))
    out, stats = [], {ev: [0, 0, 0] for ev in data.EVENTS}
    for r in rows:
        env = env_for(dt.date.fromisoformat(r["date"]))
        cells = []
        for ev, c in zip(data.EVENTS, COLS):
            mine = EXPR[ev].eval(env)
            h, m = map(int, r[c].split(":"))
            d = int((mine - (h * 3600 + m * 60)) // 60)
            stats[ev][0] += 1
            stats[ev][1] += d == 0
            stats[ev][2] = max(stats[ev][2], abs(d))
            cells.append("%s / %s%s" % (hm(mine), r[c].lstrip("0"), "" if d == 0 else " **(%+d)**" % d))
        out.append("| %s | %s |" % (r["date"], " | ".join(cells)))
    return head, out, stats


md = ["# Prayer-time accuracy report", "",
      "Generated by `generator/accuracy_report.py` from the same formulas the watch face runs.", "",
      "Settings: city **Dubai** (calibrated reference point), method **Dubai / IACAD**, Asr standard, no user adjustments.", ""]
worst, rows = astro_check()
md += ["## 1. Astronomy check", "",
       "Raw sunrise / solar noon / 18° dawn from the watch-face formulas vs PyEphem (VSOP87 high-precision ephemeris), "
       "%d checks over %d cities and 5 seasons: worst difference **%.1f seconds**." % (len(rows), len(data.CITIES), worst), ""]
for fname, title in [("iacad_dubai_2026_11.csv", "IACAD-sourced timetable (emirates247.com)"),
                     ("godubai_dubai_2026_11.csv", "Awqaf-attributed timetable (godubai.com)")]:
    head, out, stats = table(fname)
    tot = sum(v[1] for v in stats.values()); n = sum(v[0] for v in stats.values())
    md += ["## %s" % title, ""] + ["> " + h.lstrip("# ").strip() for h in head] + ["",
           "**%d of %d times identical to the minute (%.0f%%)**; largest difference %d min." % (
               tot, n, 100.0 * tot / n, max(v[2] for v in stats.values())), "",
           "| | " + " | ".join(LABEL[e] for e in data.EVENTS) + " |",
           "|---|" + "---|" * 6,
           "| exact | " + " | ".join("%d/%d" % (stats[e][1], stats[e][0]) for e in data.EVENTS) + " |", "",
           "Each cell: watch face / table. Bold = difference in minutes.", "",
           "| Date | " + " | ".join(LABEL[e] for e in data.EVENTS) + " |", "|---|" + "---|" * 6] + out + [""]
open(os.path.join(os.path.dirname(__file__), "..", "docs", "prayer_comparison.md"), "w").write("\n".join(md))
print("\n".join(md[:12]))
for fname in ("iacad_dubai_2026_11.csv", "godubai_dubai_2026_11.csv"):
    h, o, s = table(fname)
    print(fname, {k: "%d/%d max%d" % (v[1], v[0], v[2]) for k, v in s.items()})
